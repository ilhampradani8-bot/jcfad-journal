export function getArticleVersionData(slug, currentDoi) {
  if (slug && ARTICLE_VERSIONS_REGISTRY[slug]) {
    return ARTICLE_VERSIONS_REGISTRY[slug];
  }
  // Lookup by DOI if slug mismatch
  if (currentDoi) {
    const cleanDoi = currentDoi.trim();
    for (const key of Object.keys(ARTICLE_VERSIONS_REGISTRY)) {
      const entry = ARTICLE_VERSIONS_REGISTRY[key];
      if (entry.conceptDoi === cleanDoi || entry.versions.some(v => v.doi === cleanDoi)) {
        return entry;
      }
    }
  }
  return {
    conceptDoi: currentDoi || '10.5281/zenodo.14022601',
    currentVersion: '1',
    versions: [
      {
        version: 'Version 1',
        versionNum: '1',
        isLatest: true,
        date: 'Nov 2026',
        doi: currentDoi || '10.5281/zenodo.14022601',
        label: 'Official Publication',
        notes: 'Peer-reviewed research article in JCFAD.',
        url: `/${slug}`,
        zenodoUrl: `https://doi.org/${currentDoi || '10.5281/zenodo.14022601'}`
      }
    ]
  };
}
